//! The writers of the text of a table: the head every table file starts with, and the
//! constants of the tables.

use crate::ucd::{DATA_DIR, UNICODE_VERSION};

/// A source of a table: its path under `data/unicode/17.0.0/` and the SHA-256 that
/// `data/unicode/17.0.0/SOURCE` gives for it.
pub(crate) struct Source {
    pub(crate) path: String,
    pub(crate) digest: String,
}

/// The line of a table's head that names `source` and its digest.
pub(crate) fn source_line(source: &Source) -> String {
    format!("// Source: {} sha256 {}", source.path, source.digest)
}

/// The head of every table file: the line that names the generator and the sources, then one
/// line per source with its digest ([`source_line`]).
pub(crate) fn head(sources: &[Source]) -> String {
    let named: Vec<String> = sources
        .iter()
        .map(|source| format!("{DATA_DIR}/{}", source.path))
        .collect();
    let mut text = format!(
        "// Generated by swell-unicode-gen from {} (Unicode {UNICODE_VERSION}); do not edit.\n",
        named.join(", ")
    );
    for source in sources {
        text.push_str(&source_line(source));
        text.push('\n');
    }
    text
}

/// The widest array literal rustfmt keeps on one line (its `array_width`, 60 of a line of 100).
const ARRAY_WIDTH: usize = 60;

/// The widest line rustfmt writes (its `max_width`).
const MAX_WIDTH: usize = 100;

/// The constant `name` of type `&[<row>]` with `rows`, written as rustfmt writes it: on one
/// line where the array literal and the line fit its widths, else one row per line.
fn constant(name: &str, row: &str, rows: &[String]) -> String {
    let head = format!("pub(crate) const {name}: &[{row}] = &");
    let array = format!("[{}]", rows.join(", "));
    let line = format!("{head}{array};\n");
    if array.len() <= ARRAY_WIDTH && line.trim_end().len() <= MAX_WIDTH {
        return line;
    }
    let mut text = format!("{head}[\n");
    for row in rows {
        text.push_str("    ");
        text.push_str(row);
        text.push_str(",\n");
    }
    text.push_str("];\n");
    text
}

/// An error when a key of `keys` is not above the key before it.
fn ascending(name: &str, keys: impl Iterator<Item = u32>) -> Result<(), String> {
    let mut previous: Option<u32> = None;
    for key in keys {
        if previous.is_some_and(|previous| previous >= key) {
            return Err(format!(
                "{name}: the key {key:04X} is not above the key before it"
            ));
        }
        previous = Some(key);
    }
    Ok(())
}

/// The constant `name` of `pairs` `(key, value)`, sorted by key; a key that is not above the
/// key before it is an error.
pub(crate) fn pairs(name: &str, pairs: &[(u32, u32)]) -> Result<String, String> {
    ascending(name, pairs.iter().map(|(key, _)| *key))?;
    let rows: Vec<String> = pairs
        .iter()
        .map(|(key, value)| format!("({key:#06X}, {value:#06X})"))
        .collect();
    Ok(constant(name, "(u32, u32)", &rows))
}

/// The constant `name` of `mappings` `(key, code points)`, sorted by key, each key mapped to one
/// to three code points; a key that is not above the key before it, or a mapping of no or of
/// more than three code points, is an error.
pub(crate) fn mappings(name: &str, mappings: &[(u32, Vec<u32>)]) -> Result<String, String> {
    ascending(name, mappings.iter().map(|(key, _)| *key))?;
    let mut rows = Vec::with_capacity(mappings.len());
    for (key, points) in mappings {
        if !(1..=3).contains(&points.len()) {
            return Err(format!(
                "{name}: {key:04X} maps to {} code points, not one to three",
                points.len()
            ));
        }
        let points: Vec<String> = points.iter().map(|point| format!("{point:#06X}")).collect();
        rows.push(format!("({key:#06X}, &[{}])", points.join(", ")));
    }
    Ok(constant(name, "(u32, &[u32])", &rows))
}

/// The row of a constant of type `&[&[u32]]` for the sequence `points`, as rustfmt writes it at
/// the indent of a row: on one line where its items and their separators, the brackets not
/// counted, fit `array_width`, else its items as many to a line as fit `max_width`, one indent
/// deeper.
fn sequence_row(points: &[u32]) -> String {
    let items: Vec<String> = points.iter().map(|point| format!("{point:#06X}")).collect();
    let inner = items.join(", ");
    if inner.len() <= ARRAY_WIDTH {
        return format!("    &[{inner}],\n");
    }
    let indent = "        ";
    let mut text = String::from("    &[\n");
    let mut line = String::new();
    for item in &items {
        let next = if line.is_empty() {
            format!("{indent}{item},")
        } else {
            format!("{line} {item},")
        };
        if next.len() > MAX_WIDTH && !line.is_empty() {
            text.push_str(&line);
            text.push('\n');
            line = format!("{indent}{item},");
        } else {
            line = next;
        }
    }
    text.push_str(&line);
    text.push_str("\n    ],\n");
    text
}

/// The constant `name` of `sequences`, each of two code points or more, sorted by their code
/// points with none twice (so a lookup is a binary search), written as rustfmt writes it; a
/// sequence out of order, one twice, or one of fewer than two code points is an error.
pub(crate) fn sequences(name: &str, sequences: &[Vec<u32>]) -> Result<String, String> {
    for pair in sequences.windows(2) {
        if let [before, after] = pair
            && before >= after
        {
            return Err(format!(
                "{name}: the sequence {after:04X?} is not above the sequence before it"
            ));
        }
    }
    if let Some(short) = sequences.iter().find(|sequence| sequence.len() < 2) {
        return Err(format!(
            "{name}: the sequence {short:04X?} has fewer than two code points"
        ));
    }
    let head = format!("pub(crate) const {name}: &[&[u32]] = &");
    let rows: Vec<String> = sequences
        .iter()
        .map(|sequence| sequence_row(sequence))
        .collect();
    let single: Vec<&str> = rows
        .iter()
        .filter_map(|row| row.trim().strip_suffix(','))
        .filter(|row| !row.contains('\n'))
        .collect();
    let array = format!("[{}]", single.join(", "));
    let line = format!("{head}{array};\n");
    if single.len() == rows.len()
        && array.len() <= ARRAY_WIDTH
        && line.trim_end().len() <= MAX_WIDTH
    {
        return Ok(line);
    }
    let mut text = format!("{head}[\n");
    for row in &rows {
        text.push_str(row);
    }
    text.push_str("];\n");
    Ok(text)
}

/// The constant `name` of `ranges`, sorted, disjoint inclusive ranges `(first, last)`.
pub(crate) fn ranges(name: &str, ranges: &[(u32, u32)]) -> String {
    let rows: Vec<String> = ranges
        .iter()
        .map(|(first, last)| format!("({first:#06X}, {last:#06X})"))
        .collect();
    constant(name, "(u32, u32)", &rows)
}
