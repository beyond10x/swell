#!/bin/sh
# Planted defect of the gate's builds of swell's test binary (adversary pass 1 on unit
# lanebuilds): with RUSTFLAGS="-D warnings" a test module of swell that names a feature swell
# does not declare (cfg!(feature = "collect-every-safe-points"), one letter more than the
# feature) is refused by the lint unexpected_cfgs, as before tests/main.rs held the cfg
# test_modules; a typo there would make the test take its other count in silence.
# The planted workspace has one member, crates/swell: its manifest is the real one's [package],
# [[test]], [features] and [lints] sections, without dependencies; its tests are one file
# first.rs with the misspelled feature, and tests/main.rs is generated by
# taskfiles/test-main.sh write as for the real crate. The build is "cargo build --tests
# --locked" with RUSTFLAGS="-D warnings", as the task build's. Then a second file names the
# cfg test_module (one letter less than test_modules, which crates/swell/Cargo.toml declares):
# refused too; with both names spelled right the build passes.
# Run from the repository root:
#   sh tests/gate/build-refuses-a-misspelled-feature-in-a-test-module.sh
# Works only under .out/gate-tests/<name>/, which is also its cargo target directory's parent;
# prints "<name>: ok" or "<name>: FAIL <why>".

# The same output from task, cargo and ess on any machine: no colour, and no "::error" line
# that go-task adds under GITHUB_ACTIONS (gate-selftest-is-colour-proof.sh checks this).
unset CI GITHUB_ACTIONS FORCE_COLOR CLICOLOR_FORCE
export NO_COLOR=1 CARGO_TERM_COLOR=never
name=build-refuses-a-misspelled-feature-in-a-test-module
dir=.out/gate-tests/$name
fail() { echo "$name: FAIL $*"; exit 1; }

rm -rf "$dir" && mkdir -p "$dir/crates/swell/src" "$dir/crates/swell/tests" || fail "cannot make $dir"
for file in Cargo.toml clippy.toml crates/swell/Cargo.toml taskfiles/test-main.sh; do
  [ -f "$file" ] || fail "no $file to copy"
done
cp clippy.toml "$dir/clippy.toml" || fail "cannot copy clippy.toml"
{
  printf '[workspace]\nmembers = ["crates/swell"]\nresolver = "3"\n\n'
  awk '/^\[/ { keep = ($0 == "[workspace.package]" || $0 ~ /^\[workspace\.lints[].]/ || $0 ~ /^\[profile[].]/) } keep' Cargo.toml
} > "$dir/Cargo.toml" || fail "cannot write the planted Cargo.toml"
awk '/^\[/ { keep = ($0 == "[package]" || $0 == "[[test]]" || $0 == "[features]" || $0 ~ /^\[lints[].]/) } keep' crates/swell/Cargo.toml \
  > "$dir/crates/swell/Cargo.toml" || fail "cannot write the planted crates/swell/Cargo.toml"
grep -qx 'collect-every-safe-point = \[\]' "$dir/crates/swell/Cargo.toml" ||
  fail "the planted manifest does not declare the feature collect-every-safe-point"
printf '#![forbid(unsafe_code)]\n//! A planted engine crate.\n' > "$dir/crates/swell/src/lib.rs" || fail "cannot write the planted lib.rs"
printf '//! A planted test file.\n\n#[test]\nfn takes_the_collect_count() {\n    assert!(!cfg!(feature = "collect-every-safe-points"));\n}\n' \
  > "$dir/crates/swell/tests/first.rs" || fail "cannot write the planted first.rs"
GATE_CRATES=$dir/crates sh taskfiles/test-main.sh write > "$dir/write.out" 2>&1 ||
  fail "taskfiles/test-main.sh write failed on the planted crate ($dir/write.out)"
(cd "$dir" && cargo generate-lockfile --offline) > "$dir/lock.log" 2>&1 ||
  fail "cannot make a Cargo.lock for the planted workspace (log: $dir/lock.log)"

if (cd "$dir" && RUSTFLAGS="-D warnings" cargo build --workspace --tests --locked) > "$dir/denied.log" 2>&1; then
  fail "the build accepted a test module that names the undeclared feature collect-every-safe-points (log: $dir/denied.log)"
fi
grep -qF 'unexpected `cfg` condition value: `collect-every-safe-points`' "$dir/denied.log" ||
  fail "the build failed without naming the unexpected cfg value (log: $dir/denied.log)"

# The other side (correction 1, F1): the cfg test_modules is declared, not a lint turned off, so
# a misspelled name of it in a test module (test_module, one letter less) is refused too, and
# the declared name, bare and with a value as the generated tests/main.rs writes it, is not.
printf '//! A planted test file.\n\n#[test]\nfn takes_every_module() {\n    assert!(!cfg!(test_module = "first"));\n}\n' \
  > "$dir/crates/swell/tests/second.rs" || fail "cannot write the planted second.rs"
GATE_CRATES=$dir/crates sh taskfiles/test-main.sh write > "$dir/write-second.out" 2>&1 ||
  fail "taskfiles/test-main.sh write failed on the planted crate ($dir/write-second.out)"
grep -qx '#\[cfg(any(not(test_modules), test_modules = "second"))\]' "$dir/crates/swell/tests/main.rs" ||
  fail "the generated tests/main.rs has no cfg line of second ($dir/crates/swell/tests/main.rs)"
if (cd "$dir" && RUSTFLAGS="-D warnings" cargo build --workspace --tests --locked) > "$dir/name.log" 2>&1; then
  fail "the build accepted a test module that names the undeclared cfg test_module (log: $dir/name.log)"
fi
grep -qF 'unexpected `cfg` condition name: `test_module`' "$dir/name.log" ||
  fail "the build failed without naming the unexpected cfg name test_module (log: $dir/name.log)"
grep -F 'unexpected `cfg`' "$dir/name.log" | grep -qF '`test_modules`' &&
  fail "the build named the declared cfg test_modules as unexpected (log: $dir/name.log)"

printf '//! A planted test file.\n\n#[test]\nfn takes_the_collect_count() {\n    assert!(!cfg!(feature = "collect-every-safe-point"));\n}\n' \
  > "$dir/crates/swell/tests/first.rs" || fail "cannot write the corrected first.rs"
printf '//! A planted test file.\n\n#[test]\nfn takes_every_module() {\n    assert!(!cfg!(test_modules = "first"));\n}\n' \
  > "$dir/crates/swell/tests/second.rs" || fail "cannot write the corrected second.rs"
(cd "$dir" && RUSTFLAGS="-D warnings" cargo build --workspace --tests --locked) > "$dir/accepted.log" 2>&1 ||
  fail "the build refused the test modules with the declared feature and cfg names (log: $dir/accepted.log)"

echo "$name: ok"
