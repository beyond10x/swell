#!/bin/sh
# Planted defect of the task test-stack-profiles (taskfiles/stack-profiles.yml; story
# realm-size-lane-within-its-share, correction 1, F2): the task runs the binaries named by the
# binaries-metadata files of build-stack-profiles, and its first step is that build, so a source
# changed after a build is built again before the run, never a binary older than the sources.
# The planted workspace has one member, crates/swell: its manifest is the real one's [package],
# [[test]], [features] and [lints] sections, without dependencies; src/lib.rs has a function
# depth() that returns 1, and tests/deep.rs one test deep_one that asserts it is 1;
# tests/main.rs is generated by taskfiles/test-main.sh write as for the real crate. The tasks run
# from a copy of taskfiles/stack-profiles.yml and taskfiles/no-debug-sections.sh in the planted
# workspace, with STACK_MODULES=deep and STACK_TESTS=deep_one.
#   1. build-stack-profiles, then test-stack-profiles on the unchanged tree: passes, printing
#      "test-stack-profiles <profile>: 1 test binaries: 1 passed, 0 failed, 0 skipped" for
#      release and stack-debug, and its own build compiles nothing ("Compiling" in neither log).
#   2. depth() changed to return 2 after the build: test-stack-profiles builds again and the run
#      fails, "test-stack-profiles: the 1 stack tests did not all pass in the profile release";
#      the binary of the build before would pass.
#   3. depth() back to 1: passes again.
# Run from the repository root:
#   sh tests/gate/test-stack-profiles-runs-no-stale-binary.sh
# Works only under .out/gate-tests/<name>/, which is also its cargo target directory's parent;
# prints "<name>: ok" or "<name>: FAIL <why>".

# The same output from task, cargo and ess on any machine: no colour, and no "::error" line
# that go-task adds under GITHUB_ACTIONS (gate-selftest-is-colour-proof.sh checks this).
unset CI GITHUB_ACTIONS FORCE_COLOR CLICOLOR_FORCE STACK_MODULES STACK_TESTS STACK_TESTS_DIR
export NO_COLOR=1 CARGO_TERM_COLOR=never
name=test-stack-profiles-runs-no-stale-binary
dir=.out/gate-tests/$name
fail() { echo "$name: FAIL $*"; exit 1; }

rm -rf "$dir" && mkdir -p "$dir/crates/swell/src" "$dir/crates/swell/tests" "$dir/taskfiles" || fail "cannot make $dir"
for file in Cargo.toml crates/swell/Cargo.toml taskfiles/test-main.sh taskfiles/stack-profiles.yml taskfiles/no-debug-sections.sh; do
  [ -f "$file" ] || fail "no $file to copy"
done
cp taskfiles/stack-profiles.yml taskfiles/no-debug-sections.sh "$dir/taskfiles/" || fail "cannot copy the stack taskfile"
{
  printf '[workspace]\nmembers = ["crates/swell"]\nresolver = "3"\n\n'
  awk '/^\[/ { keep = ($0 == "[workspace.package]" || $0 ~ /^\[profile[].]/) } keep' Cargo.toml
} > "$dir/Cargo.toml" || fail "cannot write the planted Cargo.toml"
awk '/^\[/ { keep = ($0 == "[package]" || $0 == "[[test]]" || $0 == "[features]" || $0 ~ /^\[lints[].]/) } keep' crates/swell/Cargo.toml \
  > "$dir/crates/swell/Cargo.toml" || fail "cannot write the planted crates/swell/Cargo.toml"
lib() {
  printf '#![forbid(unsafe_code)]\n//! A planted engine crate.\n\n/// The planted depth.\npub fn depth() -> u32 {\n    %s\n}\n' "$1" \
    > "$dir/crates/swell/src/lib.rs" || fail "cannot write the planted lib.rs"
}
lib 1
printf '//! A planted stack test.\n\n#[test]\nfn deep_one() {\n    assert_eq!(swell::depth(), 1);\n}\n' \
  > "$dir/crates/swell/tests/deep.rs" || fail "cannot write the planted deep.rs"
GATE_CRATES=$dir/crates sh taskfiles/test-main.sh write > "$dir/write.out" 2>&1 ||
  fail "taskfiles/test-main.sh write failed on the planted crate ($dir/write.out)"
(cd "$dir" && cargo generate-lockfile --offline) > "$dir/lock.log" 2>&1 ||
  fail "cannot make a Cargo.lock for the planted workspace (log: $dir/lock.log)"

run() {
  out=$1
  shift
  task --taskfile "$dir/taskfiles/stack-profiles.yml" "$@" STACK_MODULES=deep STACK_TESTS=deep_one > "$dir/$out.out" 2>&1
}
passes() {
  out=$1
  what=$2
  run "$out" test-stack-profiles || fail "test-stack-profiles refused $what ($dir/$out.out)"
  for profile in release stack-debug; do
    grep -qxF "test-stack-profiles $profile: 1 test binaries: 1 passed, 0 failed, 0 skipped" "$dir/$out.out" ||
      fail "test-stack-profiles printed no line of 1 passed test in the profile $profile for $what ($dir/$out.out)"
  done
}

run build build-stack-profiles || fail "build-stack-profiles failed on the planted workspace ($dir/build.out)"
passes unchanged "the tree it built"
for profile in release stack-debug; do
  if grep -q 'Compiling' "$dir/.out/build-stack-profiles-$profile.log"; then
    fail "test-stack-profiles compiled again in the profile $profile on the tree it built ($dir/.out/build-stack-profiles-$profile.log)"
  fi
done

lib 2
if run changed test-stack-profiles; then
  fail "test-stack-profiles ran the binary built before depth() changed ($dir/changed.out)"
fi
grep -qxF "test-stack-profiles: the 1 stack tests did not all pass in the profile release (nextest exit 100; 1 must pass)" "$dir/changed.out" ||
  fail "test-stack-profiles did not refuse the changed tree with its line for the profile release ($dir/changed.out)"

lib 1
passes restored "the tree changed back"

echo "$name: ok"
